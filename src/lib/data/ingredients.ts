const byId = new Map(INGREDIENTS.map((i) => [i.id, i]));

// Basic Indian pantry staples every kitchen is assumed to have (the brief's
// test user has "basic spices"). These never block a recommendation and
// never show up as "missing" — salt and oil are not a shopping list.
export const ASSUMED_PANTRY = new Set([
  "salt",
  "oil",
  "water",
  "turmeric",
  "chili-powder",
  "cumin",
  "mustard-seeds",
  "garam-masala",
  "coriander-powder",
  "ginger-garlic",
]);

export function isAssumedPantry(id: string): boolean {
  return ASSUMED_PANTRY.has(id);
}

export function findIngredient(id: string): Ingredient | undefined {
  return byId.get(id);
}

export function searchIngredients(query: string): Ingredient[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return INGREDIENTS.filter((i) => {
    if (i.id === q) return true;
    if (i.name.toLowerCase().includes(q)) return true;
    return i.aliases.some((a) => a.toLowerCase().includes(q));
  });
}
